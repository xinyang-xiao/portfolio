function switchLanguage(lang){
  lang=copy[lang]?lang:'en';
  document.documentElement.lang=lang;
  document.title=({en:'XIAO XINYANG',ja:'ショウ シンオウ',zh:'肖新泱'})[lang]+' — Portfolio';
  document.querySelectorAll('[data-i18n]').forEach(el=>el.innerHTML=copy[lang][el.dataset.i18n]||el.innerHTML);
  document.querySelectorAll('[data-lang]').forEach(button=>{
    const selected=button.dataset.lang===lang;
    button.classList.toggle('active',selected);button.setAttribute('aria-pressed',String(selected));
  });
  document.querySelector('[data-control="previous"]')?.setAttribute('aria-label',copy[lang].previous);
  document.querySelector('[data-control="next"]')?.setAttribute('aria-label',copy[lang].next);
  try{localStorage.setItem('portfolio-language',lang)}catch{}
}
document.querySelectorAll('[data-lang]').forEach(button=>button.addEventListener('click',()=>switchLanguage(button.dataset.lang)));
let savedLanguage='en';
