let active=0, startX=0, startScroll=0, dragging=false, moved=false;
function highlight(){
  const target=gallery.scrollLeft+parseFloat(getComputedStyle(gallery).paddingLeft);
  let distance=Infinity;
  cards.forEach((card,i)=>{const delta=Math.abs(card.offsetLeft-target);if(delta<distance){distance=delta;active=i;}});
  cards.forEach((card,i)=>{card.classList.toggle('is-active',i===active);card.setAttribute('aria-current',String(i===active));});
  if(typeof controls!=='undefined'){
    controls.firstElementChild.disabled=active===0;
    controls.lastElementChild.disabled=active===cards.length-1;
  }
}
function selectCard(index){
  index=Math.max(0,Math.min(cards.length-1,index));
  gallery.scrollTo({left:cards[index].offsetLeft-parseFloat(getComputedStyle(gallery).paddingLeft),behavior:matchMedia('(prefers-reduced-motion: reduce)').matches?'instant':'smooth'});
}
gallery.addEventListener('scroll',highlight,{passive:true});
gallery.addEventListener('pointerdown',event=>{
  if(event.pointerType==='touch'||event.button!==0)return;
  event.preventDefault();
  dragging=true;moved=false;startX=event.clientX;startScroll=gallery.scrollLeft;
  gallery.classList.add('is-dragging');
});
window.addEventListener('pointermove',event=>{
  if(!dragging)return;
  const delta=event.clientX-startX;
  if(Math.abs(delta)>6){moved=true;gallery.scrollLeft=startScroll-delta;}
});
function endDrag(){if(!dragging)return;dragging=false;gallery.classList.remove('is-dragging');if(moved)selectCard(active);}
window.addEventListener('pointerup',endDrag);
window.addEventListener('pointercancel',endDrag);
gallery.addEventListener('dragstart',event=>event.preventDefault());
gallery.addEventListener('click',event=>{if(moved){event.preventDefault();moved=false;return;}const card=event.target.closest('.gallery-card');if(card&&!card.classList.contains('is-active')){event.preventDefault();selectCard(cards.indexOf(card));}});
gallery.addEventListener('keydown',event=>{if(event.key==='ArrowRight'||event.key==='ArrowLeft'){event.preventDefault();selectCard(active+(event.key==='ArrowRight'?1:-1));}});
